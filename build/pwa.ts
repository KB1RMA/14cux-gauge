import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';
import type { BuildInfo } from '../src/buildInfo.ts';

/** Where the app fetches the published build from; never cached. */
export const VERSION_FILE = 'version.json';
export const SERVICE_WORKER_FILE = 'sw.js';
export const CACHE_PREFIX = '14cux-gauge-';

/** Files that are not part of the offline copy. */
const NOT_PRECACHED = new Set([VERSION_FILE, SERVICE_WORKER_FILE]);

function listFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory()
        ? listFiles(join(dir, entry.name))
        : [join(dir, entry.name)],
    )
    .sort();
}

/**
 * The service worker. Every file of the build goes into one cache when the
 * worker installs, and is served from it from then on, so the app starts
 * without a network. A new build is a new worker with a new cache name; it
 * waits until the app asks it to take over (see `applyUpdate` in
 * `src/pwa/appStatusStore.ts`), so an update never replaces the page while
 * someone is connected to an ECU. `version.json` is not cached, which is how
 * the app learns that it is out of date.
 */
export function serviceWorkerSource(cacheName: string, urls: string[]): string {
  return `// SPDX-License-Identifier: GPL-3.0-only
// Copyright (C) 2026 14cux-gauge contributors
// Generated by build/pwa.ts.
const CACHE = ${JSON.stringify(cacheName)};
const PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const INDEX = new URL('./index.html', self.registration.scope).href;
const PRECACHE = ${JSON.stringify(urls)}.map(
  (url) => new URL(url, self.registration.scope).href,
);

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) =>
        // 'reload' skips the HTTP cache, so a half-deployed site cannot
        // leave a mix of old and new files in the offline copy.
        cache.addAll(PRECACHE.map((url) => new Request(url, { cache: 'reload' }))),
      ),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names
            .filter((name) => name.startsWith(PREFIX) && name !== CACHE)
            .map((name) => caches.delete(name)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

self.addEventListener('fetch', (event) => {
  const { request } = event;

  if (request.method !== 'GET' || !request.url.startsWith(self.registration.scope)) {
    return;
  }

  const url = new URL(request.url);

  if (request.mode === 'navigate') {
    event.respondWith(
      caches.match(INDEX).then((cached) => cached || fetch(request)),
    );
  } else if (PRECACHE.includes(url.origin + url.pathname)) {
    event.respondWith(
      caches
        .match(url.origin + url.pathname)
        .then((cached) => cached || fetch(request)),
    );
  }
});
`;
}

/**
 * Writes `version.json` and `sw.js` into a finished build. The cache name is
 * a hash of the files, so it changes exactly when the offline copy would.
 */
export function writePwaFiles(outDir: string, info: BuildInfo): void {
  const files = listFiles(outDir)
    .map((file) => relative(outDir, file).split(sep).join('/'))
    .filter((file) => !file.endsWith('.map') && !NOT_PRECACHED.has(file));
  const hash = createHash('sha256');

  for (const file of files) {
    hash.update(file).update(readFileSync(join(outDir, file)));
  }

  const cacheName = `${CACHE_PREFIX}${hash.digest('hex').slice(0, 16)}`;

  writeFileSync(join(outDir, VERSION_FILE), `${JSON.stringify(info)}\n`);
  writeFileSync(
    join(outDir, SERVICE_WORKER_FILE),
    serviceWorkerSource(cacheName, ['./', ...files.map((file) => `./${file}`)]),
  );
}

export function pwa(info: BuildInfo): Plugin {
  let outDir = 'dist';

  return {
    name: '14cux-gauge:pwa',
    apply: 'build',
    configResolved(config) {
      outDir = join(config.root, config.build.outDir);
    },
    // After Vite has copied public/ into the output.
    closeBundle: {
      order: 'post',
      handler() {
        writePwaFiles(outDir, info);
      },
    },
  };
}
